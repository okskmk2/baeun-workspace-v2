-- =========================
-- MEMBER_LICENSE (회원 보유 라이선스 인스턴스)
-- * workspace_id / project_id FK는 이후 ALTER로 연결(순환 참조 방지)
-- =========================
create table member_license (
    id           bigint generated by default as identity,
    member_id    integer not null,
    license_id   bigint not null,
    status       varchar(20) not null default 'AVAILABLE',
    price        numeric(10,2) not null,
    created_at   timestamptz not null default current_timestamp,
    expires_at   timestamptz not null,
    workspace_id integer,
    project_id   integer,

    constraint pk_member_license primary key (id),
    constraint fk_member_license_member_id__member
        foreign key (member_id) references member(id) on delete cascade,
    constraint fk_member_license_license_id__license
        foreign key (license_id) references license(id),

    constraint ck_member_license_status check (status in ('AVAILABLE','USED','EXPIRED')),
    constraint ck_member_license_price check (price >= 0)
);

create index ix_member_license_member_id    on member_license(member_id);
create index ix_member_license_license_id   on member_license(license_id);
create index ix_member_license_status       on member_license(status);
create index ix_member_license_workspace_id on member_license(workspace_id);
create index ix_member_license_project_id   on member_license(project_id);

-- =========================
-- SESSION
-- =========================
create table session (
    sid        varchar not null,
    sess       json not null,
    expires_at timestamp(6) not null,
    created_at timestamptz not null default current_timestamp,

    constraint pk_session primary key (sid)
);

create index ix_session_expires_at on session(expires_at);
create index ix_session_user_id    on session ((sess ->> 'userId'));

-- =========================
-- WORKSPACE
-- (원본 member_id → owner_id 로 명확화)
-- (원본 license_id → member_license_id 로 명확화)
-- =========================
create table workspace (
    id                integer generated by default as identity,
    name              varchar(100) not null,
    owner_id          integer,
    sort_order        integer not null default 0,
    avatar_url        varchar(512),
    theme_json        jsonb,
    is_default        boolean not null default false,
    member_license_id bigint,

    constraint pk_workspace primary key (id),
    constraint fk_workspace_owner_id__member
        foreign key (owner_id) references member(id) on delete set null,
    constraint fk_workspace_member_license_id__member_license
        foreign key (member_license_id) references member_license(id),
    constraint ck_workspace_sort_order check (sort_order >= 0)
);

create index ix_workspace_owner_id on workspace(owner_id);

-- member_license.workspace_id FK 연결(순환 참조 해소)
alter table member_license
    add constraint fk_member_license_workspace_id__workspace
        foreign key (workspace_id) references workspace(id);

-- =========================
-- PROJECT
-- (원본 license_id → member_license_id 로 명확화)
-- =========================
create table project (
    id                integer generated by default as identity,
    name              varchar(100) not null,
    workspace_id      integer not null,
    sort_order        integer not null default 0,
    avatar_url        varchar(512),
    theme_json        jsonb,
    created_at        timestamptz not null default current_timestamp,
    is_default        boolean not null default false,
    member_license_id bigint,

    constraint pk_project primary key (id),
    constraint fk_project_workspace_id__workspace
        foreign key (workspace_id) references workspace(id) on delete cascade,
    constraint fk_project_member_license_id__member_license
        foreign key (member_license_id) references member_license(id),
    constraint ck_project_sort_order check (sort_order >= 0)
);

create index ix_project_workspace_id on project(workspace_id);

-- member_license.project_id FK 연결(순환 참조 해소)
alter table member_license
    add constraint fk_member_license_project_id__project
        foreign key (project_id) references project(id);

