-- =========================
-- NOTIFICATION
-- =========================
create table notification (
    id            bigint generated by default as identity,
    recipient_id  integer not null,
    actor_id      integer,
    type          varchar(60) not null,
    resource_type varchar(30),
    resource_id   bigint,
    project_id    integer,
    workspace_id  integer,
    title         varchar(255) not null,
    body          text,
    payload       jsonb not null default '{}'::jsonb,
    is_read       boolean not null default false,
    created_at    timestamptz not null default current_timestamp,
    read_at       timestamptz,

    constraint pk_notification primary key (id),

    constraint fk_notification_recipient_id__member
        foreign key (recipient_id) references member(id) on delete cascade,
    constraint fk_notification_actor_id__member
        foreign key (actor_id) references member(id) on delete set null
);

create index ix_notification_recipient_read_created
    on notification (recipient_id asc, is_read asc, created_at desc);
create index ix_notification_recipient_created
    on notification (recipient_id asc, created_at desc);
create index ix_notification_project_id
    on notification (project_id);
create index ix_notification_workspace_id
    on notification (workspace_id);

-- =========================
-- PAYMENT
-- (원본 payment.license_id(member_license 참조) → member_license_id로 명확화)
-- =========================
create table payment (
    id                bigint generated by default as identity,
    member_id         integer not null,
    member_license_id bigint,
    amount            numeric(10,2) not null,
    payment_method    varchar(50) not null,
    transaction_ref   varchar(255),
    created_at        timestamptz not null default current_timestamp,

    constraint pk_payment primary key (id),

    constraint fk_payment_member_id__member
        foreign key (member_id) references member(id),
    constraint fk_payment_member_license_id__member_license
        foreign key (member_license_id) references member_license(id),

    constraint ck_payment_amount check (amount > 0)
);

create index ix_payment_member_license_id on payment(member_license_id);